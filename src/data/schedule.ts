export function validateSchedule(schedule: Match[] = INITIAL_SCHEDULE): {
  isValid: boolean;
  totalMatches: number;
  matchesPerTeam: Record<string, number>;
  pairCounts: Record<string, number>;
  errors: string[];
} {
  const errors: string[] = [];
  const totalMatches = schedule.length;
  const matchesPerTeam: Record<string, number> = {};
  const pairCounts: Record<string, number> = {};

  if (totalMatches !== 72) {
    errors.push(`Expected 72 total matches, got ${totalMatches}`);
  }

  schedule.forEach((match) => {
    if (match.homeTeam === match.awayTeam) {
      errors.push(`Invalid match ${match.id}: Team ${match.homeTeam} cannot play itself`);
    }

    matchesPerTeam[match.homeTeam] = (matchesPerTeam[match.homeTeam] || 0) + 1;
    matchesPerTeam[match.awayTeam] = (matchesPerTeam[match.awayTeam] || 0) + 1;

    const pairKey = [match.homeTeam, match.awayTeam].sort().join('_vs_');
    pairCounts[pairKey] = (pairCounts[pairKey] || 0) + 1;
  });

  Object.entries(matchesPerTeam).forEach(([teamId, count]) => {
    if (count !== 16) {
      errors.push(`Team ${teamId} has ${count} matches (expected 16)`);
    }
  });

  Object.entries(pairCounts).forEach(([pair, count]) => {
    if (count !== 2) {
      errors.push(`Pair ${pair} meets ${count} times (expected 2)`);
    }
  });

  return {
    isValid: errors.length === 0,
    totalMatches,
    matchesPerTeam,
    pairCounts,
    errors
  };
}
